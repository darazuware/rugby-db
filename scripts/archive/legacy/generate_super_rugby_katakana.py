def extract_players(md_path: str) -> list[dict]:
    slug = os.path.basename(md_path).replace(".md", "")
    with open(md_path, encoding="utf-8") as f:
        content = f.read()
    pattern = r"\*\*([A-Za-z][A-Za-z'\-\s\.]+)\*\*（([^）]+)）(?:、([A-Za-z\s\-]+?)(?:\s+\((\d+)\))?)?"
    players = []
    for m in re.finditer(pattern, content):
        players.append({
            "name_en": m.group(1).strip(),
            "position": m.group(2).strip(),
            "country": m.group(3).strip() if m.group(3) else None,
            "caps": int(m.group(4)) if m.group(4) else None,
            "team_slug": slug,
        })
    return players


def main():
    all_players = []
    for fname in sorted(os.listdir(TEAMS_DIR)):
        if fname.endswith(".md"):
            players = extract_players(os.path.join(TEAMS_DIR, fname))
            all_players.extend(players)
            print(f"  {fname}: {len(players)}名")

    print(f"\n合計: {len(all_players)}名")

    output = []
    matched = 0
    for p in all_players:
        entry = dict(p)
        name_ja = KATAKANA_MAP.get(p["name_en"])
        entry["name_ja"] = name_ja if name_ja else p["name_en"]
        entry["katakana_status"] = "mapped" if name_ja else "fallback"
        if name_ja:
            matched += 1
        output.append(entry)

    os.makedirs("data", exist_ok=True)
    with open(OUTPUT_FILE, "w", encoding="utf-8") as f:
        json.dump(output, f, ensure_ascii=False, indent=2)

    fallback = [p for p in output if p["katakana_status"] == "fallback"]
    print(f"マッピング済み: {matched}名 / フォールバック: {len(fallback)}名")
    print(f"出力: {OUTPUT_FILE}")
    if fallback:
        print("\n未変換（要確認）:")
        for p in fallback:
            print(f"  {p['name_en']} ({p['team_slug']})")


if __name__ == "__main__":
    main()

import asyncio, json, subprocess, edge_tts

# ep03 ナレーション（ナレーターのみ / ja-JP-NanamiNeural）
# 時制に依存する表現（W杯・大会名・年）は入れない = YouTubeストック用
LINES = [
    ("e1", "ラグビー超入門。今日は、ポジションの話です。15人がどう分かれていて、どんな役割なのか。それと、交代のルールまで見ていきます。"),
    ("e2", "ラグビーは1チーム15人。この15人は、フォワード8人と、バックス7人。大きく2つのグループに分かれます。"),
    ("e3", "背番号は、そのまま役割を表します。1番から8番までがフォワード。9番から15番までがバックス。番号を見れば、その選手が何をする人か分かります。"),
    ("e4", "フォワードは、ボールを奪って確保する役割。体で押し込んで前へ進みます。スクラムもラインアウトもフォワードの仕事。体の大きい選手が集まります。"),
    ("e5", "バックスは、そのボールを受けて、走る役割。パスやキックでスペースを突いて、トライを取りにいきます。足が速くて、判断の早い選手が並びます。"),
    ("e6", "つまり、フォワードがボールを取ってきて、バックスが仕留める。これがラグビーの、基本の分担です。"),
    ("e7", "そして交代。試合に出るのは15人ですが、メンバー登録は23人。残りの8人がリザーブです。"),
    ("e8", "ラグビーの交代は、サッカーとちがって、一度交代でしりぞいた選手は、原則もう戻れません。"),
    ("e9", "ただし、例外が3つあります。ひとつ、出血して一時的に外に出た場合。ふたつ、頭への衝撃をチェックする、HIAの場合。みっつ、フロントローの選手がケガをして、専門の選手がいなくなる場合。この3つは、戻ることが認められています。"),
    ("e10", "フォワード8人、バックス7人。まずは、この分かれ方だけ覚えれば十分です。次の動画からは、1番の選手はどんな人か、といったところを、ひとつずつ見ていきます。"),
]


async def main():
    durs = {}
    for key, text in LINES:
        path = f"audio/{key}.mp3"
        await edge_tts.Communicate(text, "ja-JP-NanamiNeural").save(path)
        d = float(subprocess.check_output(
            ["ffprobe", "-v", "quiet", "-show_entries", "format=duration", "-of", "csv=p=0", path]))
        durs[key] = round(d, 3)
        print(key, durs[key])
    json.dump(durs, open("durations.json", "w"), indent=1)


asyncio.run(main())

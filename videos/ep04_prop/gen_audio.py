# ep04 ナレーション（ナレーターのみ / ja-JP-NanamiNeural）
# 時制に依存する表現（W杯・大会名・年）は入れない = YouTubeストック用
LINES = [
    ("e1", "ラグビー超入門、ポジション編。今日は、1番と3番。プロップです。名前は同じプロップなのに、1番と3番は、やっていることがちがいます。"),
    ("e2", "プロップが立つのは、スクラムのいちばん前。フロントローの、両サイドです。真ん中の2番、フッカーを、左右からはさむ形になります。"),
    ("e3", "そして、この3人が、相手の3人とぶつかります。正面から見ると、6つの頭が、赤、青、赤、青と、交互にかみ合います。"),
    ("e4", "左に立つ1番は、ルースヘッド。組んだとき、頭の左側には、相手がいません。外側があいている。だから、ルース、つまり、ゆるいヘッドです。"),
    ("e5", "いっぽう、右に立つ3番は、タイトヘッド。相手のフッカーと、相手の1番の、あいだに頭を差し込みます。両側からはさまれる。だから、タイト、つまり、きついヘッドです。"),
    ("e6", "同じプロップでも、1番は片側だけ、3番は両側から圧力を受ける。この差は、とても大きい。だから3番には、重くて、押しに強い選手が選ばれることが多いです。"),
    ("e7", "スクラム以外の仕事もあります。ラインアウトでは、味方を持ち上げるリフター。密集では、体を入れてボールを守る。試合中ずっと、力を使い続けるポジションです。"),
    ("e8", "そしてプロップは、専門職です。組み方をまちがえると、首や背中に、大きなケガをします。だから、代わりがききません。メンバー23人には、必ず、フロントローの交代要員が入っています。"),
    ("e9", "1番はルースヘッド。3番はタイトヘッド。同じプロップでも、頭の入れ方がちがう。次は、そのあいだにいる2番、フッカーを見ていきます。"),
]


async def main():
    durs = {}
    for key, text in LINES:
        path = f"audio/{key}.mp3"
        await edge_tts.Communicate(text, "ja-JP-NanamiNeural").save(path)
        d = float(subprocess.check_output(
            ["ffprobe", "-v", "quiet", "-show_entries", "format=duration", "-of", "csv=p=0", path]))
        durs[key] = round(d, 3)
        print(key, durs[key])
    json.dump(durs, open("durations.json", "w"), indent=1)


asyncio.run(main())
